fun colorSchemeFor(style: PaletteStyle, dark: Boolean): ColorScheme = when (style) {
    PaletteStyle.MIDNIGHT -> if (dark) MidnightDark else MidnightLight
    PaletteStyle.CINNABAR -> if (dark) CinnabarDark else CinnabarLight
    PaletteStyle.PINE -> if (dark) PineDark else PineLight
    PaletteStyle.ANTIQUE_GOLD -> if (dark) AntiqueGoldDark else AntiqueGoldLight
    PaletteStyle.BLOOM_PETAL -> if (dark) BloomPetalDark else BloomPetalLight
    PaletteStyle.BLOOM_MIST -> if (dark) BloomMistDark else BloomMistLight
    PaletteStyle.BLOOM_VERDANT -> if (dark) BloomVerdantDark else BloomVerdantLight
    PaletteStyle.BLOOM_STONE -> if (dark) BloomStoneDark else BloomStoneLight
    PaletteStyle.BLOOM_WHEAT -> if (dark) BloomWheatDark else BloomWheatLight
    PaletteStyle.BLOOM_INK -> if (dark) BloomInkDark else BloomInkLight
    PaletteStyle.BLOOM_AMBER -> if (dark) BloomAmberDark else BloomAmberLight
    PaletteStyle.BLOOM_LAPIS -> if (dark) BloomLapisDark else BloomLapisLight
    PaletteStyle.BLOOM_RIPPLE -> if (dark) BloomRippleDark else BloomRippleLight
    PaletteStyle.BLOOM_CINNABAR -> if (dark) BloomCinnabarDark else BloomCinnabarLight
    PaletteStyle.BLOOM_SAGE -> if (dark) BloomSageDark else BloomSageLight
    PaletteStyle.BLOOM_SPRING -> if (dark) BloomSpringDark else BloomSpringLight
}

